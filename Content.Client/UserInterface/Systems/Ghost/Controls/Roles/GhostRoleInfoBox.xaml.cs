using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.UserInterface.Systems.Ghost.Controls.Roles
{
    [GenerateTypedNameReferences]
    public sealed partial class GhostRoleInfoBox : BoxContainer
    {
        public GhostRoleInfoBox(string name, string description)
        {
            RobustXamlLoader.Load(this);

            Title.Text = name;
            // Beschreibungen dürfen Markup enthalten (z. B. [color=yellow][bold]CentComm[/bold][/color]); SetMessage(string) würde es als Rohtext zeigen.
            Description.SetMessage(FormattedMessage.FromMarkupPermissive(description));
        }
    }
}